const I18nContext = createContext<LanguagePreference>("en");

export function I18nProvider({ language, children }: { language: LanguagePreference; children: React.ReactNode }) {
  return <I18nContext.Provider value={language}>{children}</I18nContext.Provider>;
}

export function useT() {
  const language = useContext(I18nContext);
  return (key: string) => (language === "zh-TW" ? zh[key] : en[key]) ?? key;
}
